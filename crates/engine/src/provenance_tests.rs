//! Tests of [`crate::provenance`]: records are set, read and undone like any edit; what they mean
//! for rights is worked out the same way everywhere; hostile input and hostile project files
//! change nothing and never panic.

use super::*;
use crate::provenance::{License, Provenance, Status, Synthetic};
use serde_json::json;

fn demo() -> Session {
    let mut s = Session::default();
    s.execute("file.openDemoProject", json!({})).unwrap();
    s
}

/// The ids of the demo's media items, in order.
fn media(s: &mut Session) -> Vec<u64> {
    s.execute("provenance.list", json!({})).unwrap()["items"].as_array().unwrap().iter().map(|i| i["item"].as_u64().unwrap()).collect()
}

fn pexels() -> Value {
    json!({
        "source": "Pexels", "author": "Jane Doe", "sourceUrl": "https://www.pexels.com/video/1234/",
        "license": {"name": "Pexels License", "url": "https://www.pexels.com/license/", "commercial": true, "attributionRequired": false},
    })
}

#[test]
fn a_record_is_set_read_listed_and_undone() {
    let mut s = demo();
    let ids = media(&mut s);
    assert!(ids.len() >= 6);
    let item = ids[0];
    let none = s.execute("provenance.get", json!({"item": item})).unwrap();
    assert!(none["record"].is_null() && none["status"].is_null());
    let mut p = pexels();
    p["item"] = json!(item);
    let r = s.execute("provenance.set", p).unwrap();
    assert_eq!((r["status"].clone(), r["record"]["source"].clone()), (json!("clear"), json!("pexels")), "{r}");
    assert!(r["summary"].as_str().unwrap().contains("Pexels License") && r["summary"].as_str().unwrap().contains("by Jane Doe"), "{r}");
    assert_eq!(s.execute("provenance.get", json!({"item": item})).unwrap()["record"]["author"], "Jane Doe");
    let list = s.execute("provenance.list", json!({})).unwrap();
    assert_eq!((list["counts"]["clear"].clone(), list["unrecorded"].clone()), (json!(1), json!(ids.len() - 1)));
    // undo takes it away, redo brings it back
    s.execute("edit.undo", json!({})).unwrap();
    assert!(s.execute("provenance.get", json!({"item": item})).unwrap()["record"].is_null());
    s.execute("edit.redo", json!({})).unwrap();
    assert!(!s.execute("provenance.get", json!({"item": item})).unwrap()["record"].is_null());
    // a later set changes only what it names
    s.execute("provenance.set", json!({"item": item, "note": "from the beach shoot"})).unwrap();
    let again = s.execute("provenance.get", json!({"item": item})).unwrap();
    assert_eq!((again["record"]["author"].clone(), again["record"]["note"].clone()), (json!("Jane Doe"), json!("from the beach shoot")));
    // clear removes it, and clearing nothing says so
    assert_eq!(s.execute("provenance.set", json!({"item": item, "clear": true})).unwrap()["cleared"], true);
    assert_eq!(s.execute("provenance.set", json!({"item": item, "clear": true})).unwrap()["cleared"], false);
    assert!(s.project.ext.is_empty(), "no records, no data kept in the project");
}

#[test]
fn tags_and_rights_status_follow_what_the_source_allows() {
    let mut s = demo();
    let ids = media(&mut s);
    let status = |s: &mut Session, id: u64| s.execute("provenance.get", json!({"item": id})).unwrap()["status"].clone();
    s.execute("provenance.set", json!({"item": ids[0], "tag": "own"})).unwrap();
    assert_eq!(status(&mut s, ids[0]), "clear");
    s.execute("provenance.set", json!({"item": ids[1], "tag": "licensed", "note": "bought 2026"})).unwrap();
    assert_eq!(status(&mut s, ids[1]), "clear");
    // credit asked for
    s.execute("provenance.set", json!({"item": ids[2], "source": "wikimedia", "license": {"name": "CC BY 4.0", "commercial": true, "attributionRequired": true, "creditText": "Photo by A, CC BY 4.0"}})).unwrap();
    assert_eq!(status(&mut s, ids[2]), "credit");
    // not for commercial use
    s.execute("provenance.set", json!({"item": ids[3], "source": "web", "license": {"name": "CC BY-NC", "commercial": false, "attributionRequired": true}}))
        .unwrap();
    assert_eq!(status(&mut s, ids[3]), "risk");
    // terms not stated are a risk, not a pass
    s.execute("provenance.set", json!({"item": ids[4], "source": "web", "author": "someone"})).unwrap();
    assert_eq!(status(&mut s, ids[4]), "risk");
    // generated
    s.execute(
        "provenance.set",
        json!({"item": ids[5], "source": "generated", "tag": "own", "synthetic": {"model": "some-model", "prompt": "fog at dawn", "seed": 42}}),
    )
    .unwrap();
    let g = s.execute("provenance.get", json!({"item": ids[5]})).unwrap();
    assert_eq!((g["status"].clone(), g["record"]["synthetic"]["seed"].clone()), (json!("synthetic"), json!(42)));
    assert!(g["summary"].as_str().unwrap().contains("AI-generated by some-model"));
    // removing the synthetic flag returns it to what the licence says
    s.execute("provenance.set", json!({"item": ids[5], "synthetic": null})).unwrap();
    assert_eq!(status(&mut s, ids[5]), "clear");
    let counts = s.execute("provenance.list", json!({})).unwrap()["counts"].clone();
    assert_eq!(counts, json!({"clear": 3, "credit": 1, "risk": 2, "synthetic": 0}));
}

#[test]
fn a_subclip_uses_its_source_clips_record_and_other_items_have_none() {
    let mut s = demo();
    let ids = media(&mut s);
    // a bin, a sequence and a missing item are not media
    for bad in [json!({"item": 999_999}), json!({"item": "x"}), json!({}), json!({"item": -1})] {
        assert!(s.execute("provenance.get", bad.clone()).is_err(), "{bad}");
    }
    let seq = s.project.items.values().find(|i| matches!(i.kind, filmcraft_project::ItemKind::Sequence(_))).map(|i| i.id.0).unwrap();
    assert!(s.execute("provenance.set", json!({"item": seq, "tag": "own"})).unwrap_err().to_string().contains("not a media item"));
    s.execute("provenance.set", json!({"item": ids[0], "tag": "own"})).unwrap();
    let p = &s.project;
    let sub = p.items.values().find(|i| matches!(i.kind, filmcraft_project::ItemKind::Subclip { .. })).map(|i| i.id);
    if let Some(sub) = sub {
        assert!(crate::provenance::owner(p, sub).is_some());
    }
}

#[test]
fn records_survive_saving_and_old_projects_load_without_them() {
    let mut s = demo();
    let ids = media(&mut s);
    let mut p = pexels();
    p["item"] = json!(ids[0]);
    s.execute("provenance.set", p).unwrap();
    let json = serde_json::to_string(&*s.project).unwrap();
    let back: filmcraft_project::Project = serde_json::from_str(&json).unwrap();
    assert_eq!(crate::provenance::get(&back, filmcraft_project::ItemId(ids[0])).map(|r| r.author), Some("Jane Doe".to_string()));
    // a project from before this existed has no `ext` and loads
    let mut v: Value = serde_json::from_str(&json).unwrap();
    v.as_object_mut().unwrap().remove("ext");
    let old: filmcraft_project::Project = serde_json::from_value(v).unwrap();
    assert!(old.ext.is_empty() && crate::provenance::get(&old, filmcraft_project::ItemId(ids[0])).is_none());
    // a project with no records writes no `ext` at all
    assert!(!serde_json::to_string(&*demo().project).unwrap().contains("\"ext\""));
    // a saved subset carries only the records of the items it keeps
    let keep: std::collections::BTreeSet<_> = [filmcraft_project::ItemId(ids[1])].into_iter().collect();
    let mut with_two = (*s.project).clone();
    crate::provenance::put(&mut with_two, filmcraft_project::ItemId(ids[1]), Some(Provenance::preset("own").unwrap()));
    crate::provenance::retain_items(&mut with_two, &keep);
    assert!(
        crate::provenance::get(&with_two, filmcraft_project::ItemId(ids[0])).is_none()
            && crate::provenance::get(&with_two, filmcraft_project::ItemId(ids[1])).is_some()
    );
}

#[test]
fn a_hostile_project_file_cannot_break_or_fool_the_reader() {
    let mut s = demo();
    let ids = media(&mut s);
    let mut p = (*s.project).clone();
    p.ext.insert(
        crate::provenance::KEY.to_string(),
        json!({
            ids[0].to_string(): {"source": "x".repeat(10_000), "author": "a\u{7}b", "sourceUrl": "javascript:alert(1)", "license": {"url": "file:///etc/passwd", "commercial": "yes"}},
            ids[1].to_string(): "not an object",
            ids[2].to_string(): {"synthetic": 5},
            "not-a-number": {"source": "pexels"},
            "999999": {"source": "ghost"},
            ids[3].to_string(): {"license": {"commercial": true, "attributionRequired": false}, "hash": "ZZ12ab!!"},
        }),
    );
    p.ext.insert("something.else".to_string(), json!([1, 2, 3]));
    s.project = std::sync::Arc::new(p);
    let list = s.execute("provenance.list", json!({})).unwrap();
    assert!(list["items"].as_array().unwrap().len() >= 6);
    let first = crate::provenance::get(&s.project, filmcraft_project::ItemId(ids[0]));
    assert!(first.is_none(), "a record with a wrong type is ignored whole");
    let fourth = crate::provenance::get(&s.project, filmcraft_project::ItemId(ids[3])).unwrap();
    assert_eq!(fourth.hash, "12ab", "a hash keeps only hex digits");
    // unrelated data in the map is left alone when records change
    s.execute("provenance.set", json!({"item": ids[4], "tag": "own"})).unwrap();
    assert_eq!(s.project.ext.get("something.else"), Some(&json!([1, 2, 3])));
    // sanitizing alone fixes lengths, control characters and web addresses
    let r = Provenance {
        source: format!("PEXELS {}", "x".repeat(500)),
        author: "a\u{0}b".into(),
        source_url: "javascript:x".into(),
        license: License { url: "http://ok.test/l".into(), ..License::default() },
        synthetic: Some(Synthetic { prompt: "p".repeat(9000), ..Synthetic::default() }),
        ..Provenance::default()
    }
    .sanitized();
    assert!(r.source.len() <= 60 && r.source.starts_with("pexels") && r.author == "ab" && r.source_url.is_empty() && r.license.url == "http://ok.test/l");
    assert!(r.synthetic.unwrap().prompt.chars().count() <= 4000);
    assert_eq!(Provenance::default().status(), Status::Risk);
}

#[test]
fn hostile_parameters_are_refused_and_change_nothing() {
    let mut s = demo();
    let ids = media(&mut s);
    let item = ids[0];
    let snap = (*s.project).clone();
    let undo0 = s.history.undo.len();
    let long = "x".repeat(2000);
    let cases: Vec<Value> = vec![
        json!({}),
        json!({"item": item}),
        json!({"item": item, "tag": "free"}),
        json!({"item": item, "tag": 5}),
        json!({"item": item, "source": 5}),
        json!({"item": item, "source": long}),
        json!({"item": item, "sourceUrl": "javascript:alert(1)"}),
        json!({"item": item, "sourceUrl": "https://a b/"}),
        json!({"item": item, "license": 5}),
        json!({"item": item, "license": {"commercial": "yes"}}),
        json!({"item": item, "license": {"attributionRequired": 1}}),
        json!({"item": item, "license": {"url": "file:///x"}}),
        json!({"item": item, "license": {"nope": true}}),
        json!({"item": item, "synthetic": 5}),
        json!({"item": item, "synthetic": {"seed": -1}}),
        json!({"item": item, "synthetic": {"seed": "x"}}),
        json!({"item": item, "synthetic": {"magic": 1}}),
        json!({"item": item, "clear": "yes"}),
        json!({"item": 999_999, "tag": "own"}),
    ];
    for c in cases {
        let r = std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| s.execute("provenance.set", c.clone())));
        assert!(r.is_ok(), "panicked on {c}");
        assert!(r.unwrap().is_err(), "accepted {c}");
        assert_eq!(*s.project, snap, "{c} changed the project");
        assert_eq!(s.history.undo.len(), undo0);
    }
}

#[test]
fn the_commands_exist_and_only_the_edit_is_journaled() {
    for (id, journal) in [("provenance.get", false), ("provenance.list", false), ("provenance.set", true)] {
        let spec = crate::commands::command_specs().iter().find(|c| c.id == id).unwrap_or_else(|| panic!("{id} is missing"));
        assert_eq!(spec.journal, journal, "{id}");
    }
}
